export function searchDocuments(docs: DocumentRecord[], query: string) {
  const terms = query.split(/\s+/).map((t) => t.trim()).filter((t) => t.length >= 2)
  if (terms.length === 0) return []
  const results = []
  for (const doc of docs) {
    const pages = doc.file ? pagesByFile[doc.file] ?? [] : []
    for (const [index, text] of pages.entries()) {
      const hits = terms.filter((t) => text.includes(t)).length
      if (hits === 0) continue
      const sentence = text.split(/(?<=다\.)\s*/).find((s) => terms.some((t) => s.includes(t))) ?? text
      results.push({ documentId: doc.id, documentTitle: doc.title, page: index + 1, quote: sentence, score: hits / terms.length })
    }
  }
  return results.sort((a, b) => b.score - a.score)
}
